// Builds the card logos for Dock from two pinned sources downloaded into .downloads/ (treated as untrusted files):
//   si = Simple Icons 16.35.0 (CC0): only a single plain path is accepted; a fresh SVG is written with the fill we want.
//   la = ln-dev7/logos-apps @8bba11a: logos are their owners' trademarks (not licensed; fine for this private TV, don't publish).
//        Files are checked for anything active or external and copied as they are. They are only ever shown with <img>,
//        which never runs scripts or loads other files from an SVG.
// Any image dropped into home/assets/logos/custom/<appId>.(png|jpg|svg) wins over both.
// Output: home/assets/logos/*.svg and home/js/logos.js. Usage: node tools/build-logos.js
const fs = require('fs');
const path = require('path');

const SI = 'simple-icons-16.35.0';
const LA = 'logos-apps-8bba11a';
const root = path.resolve(__dirname, '..');
const outDir = path.join(root, 'home', 'assets', 'logos');
const customDir = path.join(outDir, 'custom');

// appId -> source file, optional white tint (for dark-coloured marks on a coloured card), logo width as % of the card
const PLAN = {
  'youtube.leanback.v4': { from: 'la', file: 'youtube-wordmark', w: 68 },
  netflix: { from: 'la', file: 'netflix-wordmark', w: 64 },
  'com.disney.disneyplus-prod': { from: 'la', file: 'disney-plus', tint: 'white', w: 58 },
  hulu: { from: 'la', file: 'hulu', w: 54 },
  'com.wbd.stream': { from: 'si', file: 'hbomax', fill: '#ffffff', w: 78, h: 100 },
  'com.peacock.tv': { from: 'la', file: 'peacock', w: 50 },
  amazon: { from: 'la', file: 'prime-video', tint: 'white', w: 66 },
  'com.apple.appletv': { from: 'si', file: 'appletv', fill: '#ffffff', w: 62, h: 80 },
  'com.tubitv.ott.tubi': { from: 'si', file: 'tubi', fill: '#ffffff', w: 60, h: 70 },
  'com.crunchyroll.webapp': { from: 'si', file: 'crunchyroll', fill: '#ffffff', w: 40, h: 62 }
  // Sling: in neither source. Pluto TV: logos-apps "pluto" is a different product (Pluto by Fairwinds), so not used.
};

const SI_SHAPE = /^<svg role="img" viewBox="0 0 24 24" xmlns="http:\/\/www\.w3\.org\/2000\/svg"><title>[^<>]*<\/title><path d="([MmLlHhVvCcSsQqTtAaZz0-9.,\s+-]+)"\/><\/svg>\s*$/;
// anything that could run, pull in another file or expand entities; internal "#id" references are fine
const LA_REJECT = /<script|\son[a-z]+\s*=|<foreignObject|<!ENTITY|<!DOCTYPE|<image|<iframe|<object|<embed|(?:xlink:)?href\s*=\s*["'](?!#)|url\(\s*["']?(?!#)/i;

// True when the file is an <svg> element, optionally after an XML declaration and comments.
// A plain scan (no regex over repeated groups), so a crafted prologue can't make it hang.
function startsWithSvg(t) {
  var i = 0;
  if (t.charCodeAt(0) === 0xfeff) i = 1;
  function ws() { while (i < t.length && /\s/.test(t[i])) i++; }
  ws();
  if (t.startsWith('<?xml', i)) { var e = t.indexOf('?>', i); if (e < 0) return false; i = e + 2; }
  for (;;) {
    ws();
    if (!t.startsWith('<!--', i)) break;
    var c = t.indexOf('-->', i + 4);
    if (c < 0) return false;
    i = c + 3;
  }
  return /^<svg[\s>]/.test(t.slice(i, i + 5));
}

fs.mkdirSync(outDir, { recursive: true });
for (const f of fs.readdirSync(outDir)) if (/\.svg$/i.test(f)) fs.unlinkSync(path.join(outDir, f));   // regenerate (custom/ untouched)

const map = {};
for (const [appId, p] of Object.entries(PLAN)) {
  const file = path.join(root, '.downloads', p.from === 'si' ? SI : LA, p.file + '.svg');
  if (!fs.existsSync(file)) { console.log('missing', p.file, '- text card stays'); continue; }
  const text = fs.readFileSync(file, 'utf8');
  const name = p.from + '-' + p.file + '.svg';
  if (p.from === 'si') {
    const m = SI_SHAPE.exec(text);
    if (!m) { console.log('rejected', p.file, '- not a single plain path'); continue; }
    fs.writeFileSync(path.join(outDir, name), '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path fill="' + p.fill + '" d="' + m[1] + '"/></svg>\n');
  } else {
    if (text.length > 60000 || !startsWithSvg(text) || LA_REJECT.test(text)) { console.log('rejected', p.file, '- failed the safety check'); continue; }
    fs.writeFileSync(path.join(outDir, name), text);
  }
  map[appId] = { src: 'assets/logos/' + name, tint: p.tint || null, w: p.w, h: p.h || 50 };
  console.log('ok', appId, '->', name);
}

if (fs.existsSync(customDir)) {
  for (const f of fs.readdirSync(customDir)) {
    const m = /^(.+)\.(png|jpg|jpeg|svg)$/i.exec(f);
    if (!m) continue;
    map[m[1]] = { src: 'assets/logos/custom/' + f, tint: null, w: 60 };
    console.log('custom', m[1], '->', f);
  }
}

const js = '// Generated by tools/build-logos.js - do not edit by hand.\n' +
  'Dock.LOGOS = ' + JSON.stringify(map, null, 2) + ';\n' +
  'Dock.LOGO_CREDIT = ' + JSON.stringify('Logos: Simple Icons 16.35.0 (CC0) and ln-dev7/logos-apps. Trademarks belong to their owners.') + ';\n';
fs.writeFileSync(path.join(root, 'home', 'js', 'logos.js'), js);
console.log('wrote home/js/logos.js with', Object.keys(map).length, 'logos');
